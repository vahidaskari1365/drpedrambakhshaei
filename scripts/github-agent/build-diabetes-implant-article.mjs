  if (b.type === "h2" && !b.id.startsWith("db-")) problems.push(`block ${i}: id h2 خارج از قرارداد db-`);
  if (b.type === "table" && (!b.head?.length || !b.rows?.length)) problems.push(`block ${i}: table ناقص`);
