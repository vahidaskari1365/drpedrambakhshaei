/**
 * پاسخ ۴۱۰ Gone — برای مسیرهای مرده وردپرس قدیمی (قبل از مهاجرت به Next.js)
 *
 * چرا ۴۱۰ و نه ۴۰۴؟
 * - ۴۱۰ به گوگل می‌گوید «این URL برای همیشه حذف شده» → سریع‌تر از ۴۰۴ از ایندکس خارج می‌شود
 * - ۴۰۴ می‌تواند موقتی تلقی شود و ماه‌ها در گزارش Pages سرچ کنسول بماند
 * - robots.txt را نباید بست؛ گوگل باید خودش ۴۱۰ را ببیند تا URL را حذف کند
 *
 * پوشش‌داده‌شده‌ها:
 * - /wp-content/**        → رسانه‌های وردپرس قدیمی (در گزارش «یافت نشد ۴۰۴» سرچ کنسول)
 * - /wp-login.php         → صفحه ورود وردپرس (هدف ربات‌ها)
 * - /xmlrpc.php           → XML-RPC وردپرس (هدف ربات‌ها)
 */
export function goneResponse(): Response {
  return new Response(null, {
    status: 410,
    headers: {
      // یک روز کش — گوگل طبق برنامه خودش دوباره می‌آید و Gone را ثبت می‌کند
      "Cache-Control": "public, max-age=86400",
    },
  });
}
